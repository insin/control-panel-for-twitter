import fs from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'

import { createBrowserAction } from './lib.mjs'

/** @param {{edition?: 'v4' | 'v5', local?: boolean}} [options] */
export function prepareSafari({ edition = 'v4', local = false } = {}) {
  if (local && edition != 'v5') throw new Error('--local requires --edition=v5')

  const manifestPath = `manifest${edition == 'v4' ? '.v4' : ''}.mv3.json`
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
  manifest.description = '__MSG_extensionDescriptionShort__'
  manifest.icons = Object.fromEntries(
    [48, 96, 128, 256, 512].map((size) => [size, `icons/icon${size}.png`]),
  )
  manifest.options_ui.browser_style = true
  manifest.action.default_icon = Object.fromEntries(
    [16, 19, 32, 38, 48, 72].map((size) => [size, `icons/toolbar-icon${size}.png`]),
  )

  const require = createRequire(path.resolve('package.json'))
  const config = require(`./web-ext-config.${edition}.js`)
  // Use the edition's packaging exclusions
  const excludedFiles = config.ignoreFiles.filter((file) => !file.startsWith('!') && file != '**/*')
  let manifestJson = JSON.stringify(manifest, null, 2)
  if (local) {
    manifestJson = manifestJson.replaceAll('"https://pro.soitis.dev/*"', '"http://localhost/*", $&')
  }

  fs.mkdirSync('safari/Generated', { recursive: true })
  fs.writeFileSync('safari/Generated/manifest.json', `${manifestJson}\n`)
  fs.writeFileSync(
    'safari/Generated/Extension.xcconfig',
    [
      '// Generated by npm run prepare-safari. Do not edit.',
      `MARKETING_VERSION = ${manifest.version}`,
      `EXCLUDED_SOURCE_FILE_NAMES = $(inherited) ${excludedFiles.join(' ')}`.trimEnd(),
      '',
    ].join('\n'),
  )
  createBrowserAction()
  console.log(
    `Prepared Safari ${edition} (${manifest.version})${local ? ' with localhost access' : ''}`,
  )
}
